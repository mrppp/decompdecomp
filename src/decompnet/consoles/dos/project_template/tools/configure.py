#!/usr/bin/env python3
"""Write build.ninja and objdiff.json for a 32-bit DOS decompilation.

    python tools/configure.py VERSION

The compiler: DOS_CC, else the OpenWatcom decompdecomp installed (its toolchains folder), else wcc386 on PATH.
Its flags: DOS_FLAGS, else the project manifest's "dos_flags", else Watcom's for a Pentium-era game,
"-zq -bt=dos -mf -5r -ox". A source file may build with flags of its own (the manifest's "dos_flags_map":
{"src/auto/<file>.c": "flags"}), as try_compiler records a match with them. Made by decompdecomp.
"""

import argparse
import json
import os
import shlex
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MANIFEST = ROOT / ".decomp.wtf.json"
DEFAULT_FLAGS = "-zq -bt=dos -mf -5r -ox"


def find_compiler() -> str:
    given = os.environ.get("DOS_CC")
    if given:
        return given
    try:  # the project builds under the app's Python, where its pinned toolchains are
        from decompnet import toolchains
        if toolchains.installed("openwatcom-2.0"):
            return str(toolchains.path("openwatcom-2.0") / "binl64" / "wcc386")
    except Exception:
        pass
    return shutil.which("wcc386") or "wcc386"


def q(argv: list[str]) -> str:
    return shlex.join(argv)


def main() -> None:
    parser = argparse.ArgumentParser(description="Writes build.ninja and objdiff.json")
    parser.add_argument("version", help="game version (a directory in config/)")
    args = parser.parse_args()
    os.chdir(ROOT)
    cc = find_compiler()
    try:
        manifest = json.loads(MANIFEST.read_text(encoding="utf-8")) if MANIFEST.is_file() else {}
    except (OSError, ValueError):
        manifest = {}
    flags = os.environ.get("DOS_FLAGS") or manifest.get("dos_flags") or DEFAULT_FLAGS
    per_file = {str(k).replace("\\", "/").lstrip("./"): v for k, v in (manifest.get("dos_flags_map") or {}).items()}
    config = Path("config") / args.version / "functions.json"
    build = Path("build") / args.version
    units = json.loads(config.read_text(encoding="utf-8"))["units"]
    variants = [flags] + sorted({f for f in per_file.values() if f and f != flags})
    rule = {f: "cc" if i == 0 else f"cc{i}" for i, f in enumerate(variants)}

    lines = ["# generated by tools/configure.py; set DOS_FLAGS or the manifest's dos_flags instead",
             f"rule delink\n  command = {q([sys.executable, 'tools/delink.py', str(config), str(build / 'target')])}"
             f"\n  description = DELINK {config}\n  restat = 1"]
    for f in variants:
        command = q([sys.executable, "tools/compile.py", "--compiler", cc, "--include", "include", "--output", "$out",
                     "--source", "$in", "--config", str(config), "--", *f.split()])
        lines.append(f"rule {rule[f]}\n  command = {command}\n  description = CC $in")
    objects = [str(build / "src" / "auto" / f"{u}.o") for u in units]
    targets = [str(build / "target" / f"{u}.o") for u in units]
    lines.append(f"build {' '.join(targets)}: delink {config} tools/delink.py tools/omf2elf.py")
    for unit, obj in zip(units, objects):
        source = f"src/auto/{unit}.c"
        lines.append(f"build {obj}: {rule[per_file.get(source) or flags]} {source} | tools/compile.py tools/omf2elf.py "
                     f"{config}")
    rebuilt = build / "code.bin"
    lines.append(f"rule rebuild\n  command = {q([sys.executable, 'tools/rebuild.py', str(config), str(build), str(rebuilt)])}"
                 "\n  description = REBUILD (compared with your copy)")
    lines.append(f"build {rebuilt}: rebuild {' '.join([*targets, *objects])} | tools/rebuild.py")
    lines += [f"build rebuild: phony {rebuilt}", "build prepare-targets: phony " + " ".join(targets),
              "build prepare: phony " + " ".join(["prepare-targets", *objects]), "default prepare"]
    Path("build.ninja").write_text("\n".join(lines) + "\n", encoding="utf-8")
    objdiff = {
        "$schema": "https://raw.githubusercontent.com/encounter/objdiff/main/config.schema.json",
        "custom_make": "ninja", "custom_args": [], "build_target": False, "build_base": True,
        "watch_patterns": ["*.c", "*.h"],
        "options": {"functionRelocDiffs": "all", "combineTextSections": True},
        "units": [{"name": u, "target_path": t, "base_path": o,
                   "metadata": {"source_path": f"src/auto/{u}.c", "complete": False}}
                  for u, t, o in zip(units, targets, objects)],
    }
    Path("objdiff.json").write_text(json.dumps(objdiff, indent=2) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
