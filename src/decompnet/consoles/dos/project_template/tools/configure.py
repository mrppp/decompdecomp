#!/usr/bin/env python3
"""Write build.ninja and objdiff.json for a 32-bit DOS decompilation.

    python tools/configure.py VERSION

The compiler: DOS_CC, else the OpenWatcom decompdecomp installed (its toolchains folder), else wcc386 on PATH. A
source file may build with a Watcom of the user's own (decompdecomp passes each copy as --own
VERSION=RUNNER,EXE,HEADERS...; the manifest's "dos_compilers_map" names a file's, "compiler" the project's).
Its flags: DOS_FLAGS, else the project manifest's "dos_flags", else Watcom's for a Pentium-era game,
"-zq -bt=dos -mf -5r -ox". A source file may build with flags of its own (the manifest's "dos_flags_map":
{"src/auto/<file>.c": "flags"}), as try_compiler records a match with them. Made by decompdecomp.
"""

import argparse
import json
import os
import shlex
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MANIFEST = ROOT / ".decomp.wtf.json"
DEFAULT_FLAGS = "-zq -bt=dos -mf -5r -ox"


def find_compiler() -> str:
    given = os.environ.get("DOS_CC")
    if given:
        return given
    try:  # the project builds under the app's Python, where its pinned toolchains are
        from decompnet import toolchains
        if toolchains.installed("openwatcom-2.0"):
            return str(toolchains.path("openwatcom-2.0") / "binl64" / "wcc386")
    except Exception:
        pass
    return shutil.which("wcc386") or "wcc386"


def q(argv: list[str]) -> str:
    return shlex.join(argv)


def main() -> None:
    parser = argparse.ArgumentParser(description="Writes build.ninja and objdiff.json")
    parser.add_argument("version", help="game version (a directory in config/)")
    parser.add_argument("--own", action="append", default=[],
                        help="a compiler of your own: VERSION=RUNNER,EXE,HEADERS... (decompdecomp passes these)")
    args = parser.parse_args()
    os.chdir(ROOT)
    cc = find_compiler()
    own = {}
    specs = list(args.own)
    if not specs:  # run again by ninja (build.ninja's own rule) or by hand: the app's Watcom copies, where it is
        try:
            from decompnet import kits
            specs = [f"{c.version}={c.runner or 'none'}," + ",".join([str(c.exe), *map(str, c.includes)])
                     for c in kits.compilers(("watcom",))]
        except Exception:
            specs = []
    for spec in specs:
        version, _, rest = spec.partition("=")
        runner, exe, *headers = rest.split(",")
        own[version] = (runner, exe, headers)
    try:
        manifest = json.loads(MANIFEST.read_text(encoding="utf-8")) if MANIFEST.is_file() else {}
    except (OSError, ValueError):
        manifest = {}
    flags = os.environ.get("DOS_FLAGS") or manifest.get("dos_flags") or DEFAULT_FLAGS
    per_file = {str(k).replace("\\", "/").lstrip("./"): v for k, v in (manifest.get("dos_flags_map") or {}).items()}
    config = Path("config") / args.version / "functions.json"
    build = Path("build") / args.version
    units = json.loads(config.read_text(encoding="utf-8"))["units"]
    compilers = {str(k).replace("\\", "/").lstrip("./"): v for k, v in (manifest.get("dos_compilers_map") or {}).items()}
    project_compiler = manifest.get("compiler") or "openwatcom-2.0"

    def compiler_of(source: str) -> str:
        """A file's compiler: one that isn't set up here builds nothing (a rule that says so), never another in its
        place, which would pass for it."""
        return compilers.get(source) or project_compiler
    units_sources = [f"src/auto/{u}.c" for u in units]
    variants = sorted({(compiler_of(src), per_file.get(src) or flags) for src in units_sources},
                      key=lambda v: (v != ("openwatcom-2.0", flags), v))
    rule = {v: "cc" if i == 0 else f"cc{i}" for i, v in enumerate(variants)}

    lines = ["# generated by tools/configure.py; set DOS_FLAGS or the manifest's dos_flags instead",
             f"rule delink\n  command = {q([sys.executable, 'tools/delink.py', str(config), str(build / 'target')])}"
             f"\n  description = DELINK {config}\n  restat = 1"]
    for v in variants:
        compiler, f = v
        if compiler == "openwatcom-2.0":
            how = ["--compiler", cc]
        elif compiler not in own:
            why = (f"{compiler} isn't set up on this computer: add your copy in decompdecomp's Setup (Watcom C, your own "
                   "copy), then set the project up again")
            lines.append(f"rule {rule[v]}\n  command = {q([sys.executable, '-c', f'import sys; sys.exit({why!r})'])}"
                         f"\n  description = CC $in ({compiler}: not set up)")
            continue
        else:
            runner, exe, headers = own[compiler]
            how = ["--compiler", exe, "--runner", runner, *(a for h in headers for a in ("--system-include", h))]
        command = q([sys.executable, "tools/compile.py", *how, "--include", "include", "--output", "$out",
                     "--source", "$in", "--config", str(config), "--", *f.split()])
        lines.append(f"rule {rule[v]}\n  command = {command}\n  description = CC $in ({compiler})")
    objects = [str(build / "src" / "auto" / f"{u}.o") for u in units]
    targets = [str(build / "target" / f"{u}.o") for u in units]
    lines.append(f"build {' '.join(targets)}: delink {config} tools/delink.py tools/omf2elf.py")
    for unit, obj in zip(units, objects):
        source = f"src/auto/{unit}.c"
        lines.append(f"build {obj}: {rule[(compiler_of(source), per_file.get(source) or flags)]} {source} | "
                     "tools/compile.py tools/omf2elf.py "
                     f"{config}")
    rebuilt = build / "code.bin"
    lines.append(f"rule rebuild\n  command = {q([sys.executable, 'tools/rebuild.py', str(config), str(build), str(rebuilt)])}"
                 "\n  description = REBUILD (compared with your copy)")
    lines.append(f"build {rebuilt}: rebuild {' '.join([*targets, *objects])} | tools/rebuild.py")
    # build.ninja writes itself again when what it was made from changes: the manifest (a file's own flags or
    # compiler: search_flags, try_compiler), the config (a split or join adds a file), this script. Its arguments
    # come along (a Watcom of the user's own: --own)
    lines.append(f"rule configure\n  command = {q([sys.executable, 'tools/configure.py', *sys.argv[1:]])}"
                 "\n  description = CONFIGURE\n  generator = 1")
    lines.append(f"build build.ninja: configure | tools/configure.py {MANIFEST.relative_to(ROOT).as_posix()} {config}")
    lines += [f"build rebuild: phony {rebuilt}", "build prepare-targets: phony " + " ".join(targets),
              "build prepare: phony " + " ".join(["prepare-targets", *objects]), "default prepare"]
    Path("build.ninja").write_text("\n".join(lines) + "\n", encoding="utf-8")
    objdiff = {
        "$schema": "https://raw.githubusercontent.com/encounter/objdiff/main/config.schema.json",
        "custom_make": "ninja", "custom_args": [], "build_target": False, "build_base": True,
        "watch_patterns": ["*.c", "*.h"],
        "options": {"functionRelocDiffs": "all", "combineTextSections": True},
        "units": [{"name": u, "target_path": t, "base_path": o,
                   "metadata": {"source_path": f"src/auto/{u}.c", "complete": False}}
                  for u, t, o in zip(units, targets, objects)],
    }
    Path("objdiff.json").write_text(json.dumps(objdiff, indent=2) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
